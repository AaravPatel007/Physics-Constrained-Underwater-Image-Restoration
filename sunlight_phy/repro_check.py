"""Is the baseline retrained on this machine the same model as the original baseline_v1_60ep_bigdata?

The original checkpoint is not in the repository (*.pt is git-ignored), so the baseline was retrained here with the
unchanged src/train.py and v1's arguments. This compares it with every committed v1 number that used the same
protocol. Rows marked "data check" compare quantities that do not depend on the network at all (raw image,
true-coefficient oracle): they must match closely, or the rebuilt test data differ from the original.

  python sunlight_phy/repro_check.py   -> results/repro_check.json, docs/03_reproduction_check.md
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent


def main():
    S = json.load(open(HERE / "results" / "synth_eval_sun.json"))
    O = json.load(open(ROOT / "results" / "synth_eval_big.json"))
    rows = []

    def add(group, what, orig, new, kind="model"):
        rows.append({"group": group, "what": what, "original_v1": orig, "retrained_here": new, "diff": new - orig, "kind": kind})

    for m in ("psnr", "ssim", "de2000"):
        add("synthetic test (654)", f"raw {m}", O["random"]["raw"][m], S["random"]["raw"][m], "data check")
        add("synthetic test (654)", f"true-coefficient oracle {m}", O["random"]["oracle (true coefs)"][m],
            S["random"]["oracle (true coefs)"][m], "data check")
        add("synthetic test (654)", f"BetaNet {m}", O["random"]["beta_rgbd_big"][m], S["random"]["baseline"][m])
    for k in ("beta_D", "beta_B", "B_inf", "E"):
        for c, ch in enumerate("RGB"):
            add("coefficient median rel. error [%]", f"{k} {ch}", O["coef_median_rel_err_pct"]["beta_rgbd_big"][k][c],
                S["coef_median_rel_err_pct"]["baseline"][k][c])
    for t, d in O["jerlov"].items():
        add("Jerlov PSNR (200 rooms)", f"{t} BetaNet", d["beta_rgbd_big"], S["jerlov"][t]["psnr|baseline"])
        add("Jerlov PSNR (200 rooms)", f"{t} raw", d["raw"], S["jerlov"][t]["psnr|raw"], "data check")

    lo = json.load(open(ROOT / "results" / "baseline_v1_60ep_bigdata" / "log.json"))
    ln = json.load(open(HERE / "runs" / "baseline_v1_repro" / "log.json"))
    sc = lambda L: min(L, key=lambda r: r["val_coef"] + 10 * r["val_img_l1"])
    for k in ("val_psnr", "val_coef", "val_img_l1"):
        add("validation (best epoch)", k, sc(lo)[k], sc(ln)[k])
    add("validation (best epoch)", "best epoch", sc(lo)["epoch"], sc(ln)["epoch"])

    rp = HERE / "results" / "real_eval_sun.json"
    if rp.exists():
        R = json.load(open(rp))
        Ob = json.load(open(ROOT / "results" / "real_eval_big.json"))
        D1b = json.load(open(ROOT / "results" / "review2_day1b_smaller_smoothing_patch" / "eval.json"))["uieb_val"]["summary"]
        U, OU = R["uieb"]["summary"], Ob["uieb"]["summary"]
        for m in ("psnr", "de2000"):
            add("UIEB val (90)", f"raw {m}", OU["raw"][m], U["raw"][m], "data check")
            add("UIEB val (90)", f"BetaNet {m}", OU["BetaNet"][m], U["baseline"][m])
            add("UIEB val (90)", f"BetaNet + gray-world {m}", OU["BetaNet + gray-world"][m], U["baseline + gray-world"][m])
            add("UIEB val (90)", f"BetaNet + Day 1b {m}", D1b["day1b"][m], U["baseline + Day 1b"][m])
        if "seathru" in R:
            for f, d in R["seathru"]["chart"].items():
                oc = Ob["seathru"]["chart"][f]
                add("Sea-thru chart [deg]", f"{f} raw", oc["raw"], d["raw"], "data check")
                add("Sea-thru chart [deg]", f"{f} BetaNet own E", oc["BetaNet [SfM range]"], d["baseline"])
                add("Sea-thru chart [deg]", f"{f} BetaNet + gray-world", oc["BetaNet + gray-world [SfM range]"],
                    d["baseline + gray-world"])
    json.dump(rows, open(HERE / "results" / "repro_check.json", "w"), indent=1)

    md = ["# Reproduction check: baseline retrained here vs the original `baseline_v1_60ep_bigdata`", "",
          "Generated by `repro_check.py`. *Original* = committed numbers (`results/synth_eval_big.json`, "
          "`results/real_eval_big.json`, `results/baseline_v1_60ep_bigdata/log.json`, Day 1b `eval.json`). "
          "*Retrained* = `sunlight_phy/runs/baseline_v1_repro`, the unchanged `src/train.py` with v1's arguments on "
          "this machine. Data-check rows do not involve any network; they show whether the rebuilt data equal the "
          "original data.", ""]
    g = None
    for r in rows:
        if r["group"] != g:
            g = r["group"]
            md += ["", f"### {g}", "", "| | original v1 | retrained here | difference | |", "|---|---|---|---|---|"]
        md.append(f"| {r['what']} | {r['original_v1']:.3f} | {r['retrained_here']:.3f} | {r['diff']:+.3f} | "
                  f"{'data check' if r['kind'] == 'data check' else ''} |")
    (HERE / "docs").mkdir(exist_ok=True)
    open(HERE / "docs" / "03_reproduction_check.md", "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
